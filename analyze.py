"""Run the full analysis: figures/ and results/summary.md are regenerated from data/.

    python analyze.py                # both runs, 18 mV cut
    python analyze.py --runs run1 --cut-mv 16
"""
import argparse
from pathlib import Path

import numpy as np

from muon import plots, stats
from muon.io import load_run

ROOT_DIR = Path(__file__).resolve().parent
THRESHOLDS = np.arange(10, 26, 1.0)  # same scan range as the original analysis


def analyze_run(run, cut_mv, fig_dir):
    events = load_run(run)
    rows = []

    poisson_fits = {role: stats.fit_poisson(stats.counts_per_second(e["time_ms"])) for role, e in events.items()}
    plots.plot_counts(poisson_fits, fig_dir / f"{run}_counts.png")

    interval_fits = {}
    for role, e in events.items():
        kept = e[e["sipm_mv"] >= cut_mv]
        interval_fits[(role, "all events")] = stats.fit_intervals(e["time_ms"], x_max=4000, skip_bins=1)
        interval_fits[(role, f"V >= {cut_mv:g} mV")] = stats.fit_intervals(kept["time_ms"], x_max=6000, skip_bins=1)
        first_bin_kept = stats.fit_intervals(e["time_ms"], x_max=4000, skip_bins=0)  # original convention
        p, f = poisson_fits[role], interval_fits[(role, "all events")]
        rows.append({
            "run": run, "role": role, "events": e.size,
            "duration_s": e["time_ms"][-1] / 1000,
            "rate_hz": f"{f['rate_hz']:.3f} +/- {f['rate_err_hz']:.3f}",
            "poisson_lambda": f"{p['lambda']:.3f}",
            "poisson_chi2_ndf": f"{p['chi2'] / p['ndf']:.2f}",
            "var_over_mean": f"{p['fano']:.3f}",
            "dead_time_frac": f"{stats.dead_time_fraction(e):.3f}",
            "gap_chi2_ndf_all_bins": f"{first_bin_kept['chi2'] / first_bin_kept['ndf']:.2f}",
            "gap_chi2_ndf_skip_first": f"{f['chi2'] / f['ndf']:.2f}",
            "rate_from_tau_hz": f"{f['rate_fit_hz']:.3f}",
            "events_after_cut": kept.size,
        })
    plots.plot_intervals(interval_fits, fig_dir / f"{run}_intervals.png")

    m, s = events["master"]["sipm_mv"], events["slave"]["sipm_mv"]
    ratio, ratio_err = stats.slave_fraction_above(m, s, THRESHOLDS)
    plots.plot_spectrum(m, s, THRESHOLDS, ratio, ratio_err, cut_mv, fig_dir / f"{run}_spectrum.png")
    scan = {"run": run, "best_mv": THRESHOLDS[np.argmax(ratio)],
            "ratio": ratio, "err": ratio_err}
    return rows, scan


def write_summary(rows, scans, path):
    headers = list(rows[0])
    lines = ["# Summary (generated by analyze.py)", "",
             "| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(f"{r[h]:.0f}" if isinstance(r[h], float) else str(r[h]) for h in headers) + " |"
              for r in rows]
    lines += ["", "## Threshold scan: N(slave, V >= v) / N(master, V >= v)", "",
              "| v [mV] | " + " | ".join(s["run"] for s in scans) + " |", "|---|" + "---|" * len(scans)]
    for i, v in enumerate(THRESHOLDS):
        lines.append(f"| {v:g} | " + " | ".join(f"{s['ratio'][i]:.3f} +/- {s['err'][i]:.3f}" for s in scans) + " |")
    lines.append("")
    lines += [f"- {s['run']}: maximum at {s['best_mv']:g} mV" for s in scans]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs", nargs="+", default=["run1", "run2"])
    parser.add_argument("--cut-mv", type=float, default=18.0, help="SiPM voltage cut for the interval plots")
    args = parser.parse_args()

    fig_dir, res_dir = ROOT_DIR / "figures", ROOT_DIR / "results"
    fig_dir.mkdir(exist_ok=True)
    res_dir.mkdir(exist_ok=True)
    rows, scans = [], []
    for run in args.runs:
        r, s = analyze_run(run, args.cut_mv, fig_dir)
        rows += r
        scans.append(s)
    write_summary(rows, scans, res_dir / "summary.md")
    print((res_dir / "summary.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
